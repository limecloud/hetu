import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, mkdir, copyFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import path from "node:path";
import os from "node:os";
import { PluginPackage } from "../src/package.ts";

const root = path.resolve(import.meta.dirname, "../../..");
const cli = path.join(root, "apps/desktop/dist/plugin-dev.mjs");
test("独立开发工具创建TS/React工程，拒绝覆盖，校验不执行包内代码", async () => {
  const folder = await mkdtemp(path.join(os.tmpdir(), "hetu-developer-")), directory = path.join(folder, "新插件");
  const create = spawnSync(process.execPath, [cli, "create", directory, "--id", "org.author.counter", "--title", "文字统计"], { encoding: "utf8" });
  assert.equal(create.status, 0, create.stderr);
  assert.deepEqual(JSON.parse(create.stdout).permissions, []);
  const capabilities = await readFile(path.join(directory, "CAPABILITIES.md"), "utf8");
  assert.ok(capabilities.includes("统计 Unicode 字符") && capabilities.includes("plugin.json"));
  const source = await readFile(path.join(directory, "src/view.tsx"), "utf8");
  assert.ok(source.includes('from "react"')); assert.ok(source.includes('from "./sdk.ts"'));
  assert.ok(!source.includes("@hetu/") && !source.includes(root));
  assert.equal(await readFile(path.join(directory, "src/sdk.ts"), "utf8"), await readFile(path.join(root, "packages/plugin-sdk/src/index.ts"), "utf8"));
  const again = spawnSync(process.execPath, [cli, "create", directory, "--id", "org.author.other", "--title", "覆盖"], { encoding: "utf8" });
  assert.notEqual(again.status, 0);
  assert.equal((JSON.parse(await readFile(path.join(directory, "plugin.json"), "utf8"))).id, "org.author.counter");
  const dist = path.join(directory, "dist");
  await mkdir(dist);
  for (const file of ["plugin.json", "index.html", "LICENSE"]) await copyFile(path.join(directory, file), path.join(dist, file));
  await writeFile(path.join(dist, "view.js"), 'throw new Error("验证器不得执行视图");');
  await writeFile(path.join(dist, "backend.mjs"), 'throw new Error("验证器不得执行后端");');
  const result = spawnSync(process.execPath, [cli, "validate", dist], { encoding: "utf8" });
  assert.equal(result.status, 0, result.stderr);
  const validated = JSON.parse(result.stdout), expected = await PluginPackage.inspect(dist);
  assert.equal(validated.package_sha256, expected.sha256);
  assert.deepEqual(validated.contributions.actions, ["count"]);
  assert.equal(validated.status, "valid");
  const manifest = JSON.parse(await readFile(path.join(dist, "plugin.json"), "utf8"));
  manifest.host_api = "999";
  await writeFile(path.join(dist, "plugin.json"), JSON.stringify(manifest));
  assert.notEqual(spawnSync(process.execPath, [cli, "validate", dist], { encoding: "utf8" }).status, 0);
  assert.equal((JSON.parse(await readFile(path.join(directory, "plugin.json"), "utf8"))).host_api, "1");
});
