async function command(page: Page, label: string) {
  const trigger = page.locator('summary[aria-label="文字操作"]');
  if (!await trigger.evaluate(element => (element.parentElement as HTMLDetailsElement).open)) await trigger.click();
  await page.locator(".editor-command-menu").getByRole("button", {name: label, exact: true}).click();
  await page.keyboard.press("Escape");
  await page.getByRole("textbox", {name: "文稿编辑", exact: true}).focus();
}

